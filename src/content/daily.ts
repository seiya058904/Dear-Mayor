import { letter } from "./author";
function d(
  title: string,
  sender: string,
  body: string,
  request: string,
  replies: [string, string, string],
) {
  return letter(
    title,
    `${body}\n恳请准许${request}。`,
    `镇里准许${request}，来信人已照办。`,
    `镇里正式拒绝${request}，来信人没有照原案办理。`,
    `有关${request}的申请未收到答复，来信人仍在等待，并未收到禁令。`,
    replies.map((text) => [text + "。", `来信人照批示另作安排：${text}。`]),
    sender,
  );
}
